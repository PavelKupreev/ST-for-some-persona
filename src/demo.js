/**
 * @param {object} card карточка ST
 * @param {number} index 0 или 1
 */
export function createDemoHero(card, index) {
    const presets = [
        {
            stats: { STR: 10, DEX: 14, CON: 12, INT: 13, WIS: 10, CHA: 15 },
            hp: 11,
            inventory: ['кинжал', 'отмычки', 'кошель с 12 серебряками'],
            microGoal: 'украсть ключ от погреба у трактирщика, чтобы никто не заметил',
        },
        {
            stats: { STR: 15, DEX: 11, CON: 14, INT: 10, WIS: 13, CHA: 9 },
            hp: 14,
            inventory: ['длинный меч', 'кольчуга', 'фляга с элем'],
            microGoal: 'выяснить, кто прислал письмо без подписи, и проверить, не ловушка ли это',
        },
    ];
    const preset = presets[index];
    return {
        cardAvatar: card.avatar,
        name: card.name,
        stats: { ...preset.stats },
        hp: { current: preset.hp, max: preset.hp },
        inventory: [...preset.inventory],
        globalGoal: `найти своё место в этом мире, следуя предыстории ${card.name}`,
        microGoal: preset.microGoal,
        silence: 0,
    };
}
